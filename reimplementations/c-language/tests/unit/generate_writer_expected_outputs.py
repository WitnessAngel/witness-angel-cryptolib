"""
Generate wa_writer_expected_outputs.h, the expected outputs of the C document writers (tasks 3.4 and 3.5):
for each sample structure, its input as CBOR with unsorted map keys (decoded by the C test into a value tree),
and wacryptolib's dump_to_json_bytes() and dump_to_cbor_bytes() of it.

Run from the repository root, in the wacryptolib environment:
    python reimplementations/c-language/tests/unit/generate_writer_expected_outputs.py
"""

import uuid
from pathlib import Path

import cbor2

from wacryptolib.utilities import dump_to_cbor_bytes, dump_to_json_bytes

OUTPUT_PATH = Path(__file__).with_name("wa_writer_expected_outputs.h")

SAMPLES = [
    # A symkey, as generated for AES_CBC (unsorted keys)
    ("symkey_aes_cbc", {"key": bytes(range(32)), "iv": bytes(range(100, 116))}),
    # Key structs (spec §6.5), with and without metadata
    (
        "key_struct_with_metadata",
        {
            "key_bytes": bytes(range(64)),
            "cryptainer_metadata": {"Café ☕": "naïve 😀", "count": 3, "neg": -70000, "flags": [True, False, None]},
        },
    ),
    ("key_struct_without_metadata", {"key_bytes": b"\xff" * 5, "cryptainer_metadata": None}),
    # A nested cipherdict, with every integer head size, a UUID and an empty byte string
    (
        "nested_cipherdict",
        {
            "tag": b"\x01" * 16,
            "ciphertext": bytes(range(37)),
            "nonce": b"\x02" * 16,
            "inner": {
                "digest_list": [b"abc", b""],
                "uuid": uuid.UUID("0f0e0d0c-0b0a-0908-0706-050403020100"),
                "big": 2**63 - 1,
                "small": -(2**63),
                "zero": 0,
                "u8": 255,
                "u16": 65535,
                "u32": 2**32 - 1,
                "u64": 2**32,
                "s1": -1,
                "s24": -24,
                "s25": -25,
                "i23": 23,
                "i24": 24,
            },
        },
    ),
    # A Shamir shard tuple (index, bytes), serialized as an array
    ("shard_tuple", (3, bytes(range(16)))),
    # Text escapes and key orders (UTF-8 bytes for Extended JSON, length first for WA-CBOR)
    (
        "text_escapes_and_key_orders",
        {
            "z": "Café ☕",
            "aa": "😀",
            "controls": "\x00\x01\x1f\x7f\x80\b\f\n\r\t\"\\/",
            "": "empty key",
            "é": 1,
            "a": "",
            "b\U0001f600": True,
        },
    ),
    # Empty containers
    ("empty_containers", {"m": {}, "l": [], "b": b""}),
]


def _to_c_string_literal(data: bytes) -> str:
    """Pure-ASCII C string literal of `data`, split in chunks of 100 characters."""
    pieces = []
    for byte in data:
        character = chr(byte)
        if character in "\"\\":
            pieces.append("\\" + character)
        elif 0x20 <= byte < 0x7F and character != "?":  # "?" avoided: trigraphs
            pieces.append(character)
        else:
            pieces.append("\\%03o" % byte)  # Always 3 digits: never merges with a following digit
    # Chunk boundaries fall between pieces, never inside an escape sequence
    chunks, current = [], ""
    for piece in pieces:
        if len(current) + len(piece) > 100:
            chunks.append(current)
            current = ""
        current += piece
    chunks.append(current)
    return "\n        ".join('"%s"' % chunk for chunk in chunks)


def main():
    lines = [
        "/* This file is part of Witness Angel Cryptolib",
        " * SPDX-FileCopyrightText: Copyright Prolifik SARL",
        " * SPDX-License-Identifier: GPL-2.0-or-later",
        " */",
        "",
        "/* GENERATED by generate_writer_expected_outputs.py from wacryptolib: do not edit. */",
        "",
        "#ifndef WA_WRITER_EXPECTED_OUTPUTS_H",
        "#define WA_WRITER_EXPECTED_OUTPUTS_H",
        "",
        "typedef struct wa_writer_expected_output {",
        "    const char *name;",
        "    const char *unsorted_input_cbor_hex;",
        "    const char *expected_extended_json;",
        "    const char *expected_wacbor_hex;",
        "} wa_writer_expected_output_t;",
        "",
        "static const wa_writer_expected_output_t wa_writer_expected_outputs[] = {",
    ]
    for name, structure in SAMPLES:
        unsorted_input = cbor2.dumps(structure)  # Keeps insertion order, UUIDs as tag 37
        expected_json = dump_to_json_bytes(structure)
        expected_cbor = dump_to_cbor_bytes(structure)
        assert expected_json.isascii()
        lines += [
            "    {",
            '        "%s",' % name,
            '        "%s",' % unsorted_input.hex(),
            "        %s," % _to_c_string_literal(expected_json),
            '        "%s",' % expected_cbor.hex(),
            "    },",
        ]
    lines += ["};", "", "#endif /* WA_WRITER_EXPECTED_OUTPUTS_H */", ""]
    OUTPUT_PATH.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print("Written", OUTPUT_PATH)


if __name__ == "__main__":
    main()
