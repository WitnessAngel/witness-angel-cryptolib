# Build and test the flightbox Rust encryptor in every configuration (design D12), on Linux or WSL:
#   - formatting and lints;
#   - RustCrypto backend with both document formats: conformance, unit tests, host tools;
#   - wolfCrypt backend with both document formats: the same, on wolfSSL sources fetched at the version pinned by
#     the C tree unless WA_WOLFSSL_SOURCE_DIR gives them;
#   - CBOR-only and JSON-only builds on the RustCrypto backend: unit tests, and the symbol check of the disabled
#     format;
#   - the footprint probe for Cortex-M33 and Cortex-M4, CBOR-only and JSON-only, with its linked code sizes;
#   - libFuzzer smoke runs of each fuzz target (nightly toolchain with cargo-fuzz), from seeds generated by Python;
#   - cargo deny.
# The tools of each build are then usable by the interop tests, the list being also written to
# <build root>/interop_build_dirs.txt:
#   WA_FLIGHTBOX_C_BUILD_DIR=<printed value> pytest reimplementations/c-language/tests/interop
#
# The steps needing optional tools (libclang for the wolfCrypt backend, arm-none-eabi binutils, a nightly toolchain
# with cargo-fuzz, cargo-deny) are skipped with a message when the tool is missing, unless WA_REQUIRE_ALL_STEPS=1.
#
# Environment variables (all optional):
#   WA_BUILD_ROOT          directory of the builds (default: reimplementations/rust/target/all)
#   WA_PYTHON              Python interpreter able to import wacryptolib's dependencies (default: python3)
#   WA_FUZZ_SECONDS        duration of each fuzz run (default: 60)
#   WA_WOLFSSL_SOURCE_DIR  wolfSSL 5.8.x source tree (default: fetched into the build directory)
#   WA_NO_FETCH            1 to never download wolfSSL: the wolfCrypt steps are then skipped without sources
#   WA_C_BUILD_ROOT        builds of the C tree to add to the interop list when they exist
#                          (default: reimplementations/c-language/build)
#   WA_REQUIRE_ALL_STEPS   1 to fail instead of skipping a step (CI)

set -euo pipefail

SOURCE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPOSITORY_DIR="$(cd "$SOURCE_DIR/../.." && pwd)"
BUILD_ROOT="${WA_BUILD_ROOT:-$SOURCE_DIR/target/all}"
PYTHON="${WA_PYTHON:-python3}"
FUZZ_SECONDS="${WA_FUZZ_SECONDS:-60}"
REQUIRE_ALL_STEPS="${WA_REQUIRE_ALL_STEPS:-0}"
EMBEDDED_TARGETS=(thumbv8m.main-none-eabihf thumbv7em-none-eabihf)

# The wolfSSL release pinned by reimplementations/c-language/CMakeLists.txt
WOLFSSL_VERSION="5.8.4-stable"
WOLFSSL_URL="https://github.com/wolfSSL/wolfssl/archive/refs/tags/v$WOLFSSL_VERSION.tar.gz"
WOLFSSL_SHA256="2b702b7a66b0067bfd284408827b1e59288b357b0dd758d0089c062395f2a522"

for tool in cargo rustfmt "$PYTHON"; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        echo "error: '$tool' not found (see the environment variables at the top of $0)" >&2
        exit 1
    fi
done

mkdir -p "$BUILD_ROOT"
cd "$SOURCE_DIR"

log_step() {
    echo
    echo "======== $* ========"
}

SKIPPED_STEPS=()

# skip_step REASON ; fails instead when every step is required
skip_step() {
    if [ "$REQUIRE_ALL_STEPS" = "1" ]; then
        echo "error: $* (WA_REQUIRE_ALL_STEPS=1)" >&2
        exit 1
    fi
    echo "SKIPPED: $*"
    SKIPPED_STEPS+=("$*")
}

# FORMATTING AND LINTS #

log_step "Formatting and lints"
cargo fmt --all --check
(cd fuzz && cargo fmt --check)
CARGO_TARGET_DIR="$BUILD_ROOT/rustcrypto" cargo clippy --all-targets -- -D warnings
CARGO_TARGET_DIR="$BUILD_ROOT/rustcrypto" RUSTDOCFLAGS="-D warnings" cargo doc --no-deps

# RUSTCRYPTO BACKEND #

log_step "rustcrypto: RustCrypto backend, JSON and CBOR"
CARGO_TARGET_DIR="$BUILD_ROOT/rustcrypto" cargo test
# The host tools themselves, which the tests of their crate do not link
CARGO_TARGET_DIR="$BUILD_ROOT/rustcrypto" cargo build
# The core crate alone has no dependency but zeroize, and builds without any document format: it then refuses
# every cryptainer creation
CARGO_TARGET_DIR="$BUILD_ROOT/rustcrypto" cargo build -p wa_flightbox --no-default-features
CARGO_TARGET_DIR="$BUILD_ROOT/rustcrypto" cargo test -p wa_flightbox --no-default-features \
    --test build_without_document_format
INTEROP_BUILD_DIRS="$BUILD_ROOT/rustcrypto/debug"

# check_no_symbol_of BINARY MODULE... ; the modules of a disabled document format must not be linked
check_no_symbol_of() {
    local binary="$1"
    shift
    local module
    for module in "$@"; do
        if nm -C "$binary" | grep -F "wa_flightbox::encoding::$module::" >/dev/null; then
            echo "error: $binary has symbols of the disabled module $module" >&2
            exit 1
        fi
    done
}

for document_format in cbor json; do
    build_name="rustcrypto_${document_format}_only"
    if [ "$document_format" = "cbor" ]; then
        feature="wa-cbor"
        disabled_modules=(extended_json_writer base64_encoder)
        enabled_module="wacbor_deterministic_writer"
    else
        feature="extended-json"
        disabled_modules=(wacbor_deterministic_writer)
        enabled_module="extended_json_writer"
    fi
    log_step "$build_name: RustCrypto backend, $document_format only"
    CARGO_TARGET_DIR="$BUILD_ROOT/$build_name" cargo test --no-default-features \
        --features "$feature,backend-rustcrypto"
    CARGO_TARGET_DIR="$BUILD_ROOT/$build_name" cargo build --no-default-features \
        --features "$feature,backend-rustcrypto"
    CARGO_TARGET_DIR="$BUILD_ROOT/$build_name" cargo clippy --all-targets --no-default-features \
        --features "$feature,backend-rustcrypto" -- -D warnings
    driver="$BUILD_ROOT/$build_name/debug/wa_flightbox_test_driver"
    # The check itself is checked: the enabled writer must be found by the same search
    if ! nm -C "$driver" | grep -F "wa_flightbox::encoding::$enabled_module::" >/dev/null; then
        echo "error: the symbol check finds no symbol of $enabled_module in $driver" >&2
        exit 1
    fi
    check_no_symbol_of "$driver" "${disabled_modules[@]}"
    INTEROP_BUILD_DIRS="$INTEROP_BUILD_DIRS:$BUILD_ROOT/$build_name/debug"
done

# The host tools refuse to build without a document format, or with two backends
log_step "Refused feature combinations of the host tools"
expect_build_failure() {
    local expected_message="$1"
    shift
    local log_file="$BUILD_ROOT/refused_build.log"
    if CARGO_TARGET_DIR="$BUILD_ROOT/rustcrypto" cargo build -p wa_flightbox_host_tools "$@" >"$log_file" 2>&1; then
        echo "error: 'cargo build -p wa_flightbox_host_tools $*' should have failed" >&2
        exit 1
    fi
    if ! grep -F "$expected_message" "$log_file" >/dev/null; then
        cat "$log_file"
        echo "error: the refused build does not say '$expected_message'" >&2
        exit 1
    fi
    echo "refused as expected: $*"
}
expect_build_failure "enable at least one document format feature" --no-default-features --features backend-rustcrypto
expect_build_failure "enable one crypto backend feature" --no-default-features --features wa-cbor

# WOLFCRYPT BACKEND #

log_step "wolfcrypt: wolfCrypt backend, JSON and CBOR"
WOLFSSL_SOURCE_DIR="${WA_WOLFSSL_SOURCE_DIR:-}"
if [ -z "$WOLFSSL_SOURCE_DIR" ] && [ "${WA_NO_FETCH:-0}" != "1" ]; then
    WOLFSSL_SOURCE_DIR="$BUILD_ROOT/wolfssl-$WOLFSSL_VERSION"
    if [ ! -f "$WOLFSSL_SOURCE_DIR/wolfcrypt/src/aes.c" ]; then
        echo "Fetching wolfSSL $WOLFSSL_VERSION"
        archive="$BUILD_ROOT/wolfssl-$WOLFSSL_VERSION.tar.gz"
        curl --fail --silent --show-error --location --output "$archive" "$WOLFSSL_URL"
        echo "$WOLFSSL_SHA256  $archive" | sha256sum --check --quiet
        rm -rf "$WOLFSSL_SOURCE_DIR"
        mkdir -p "$WOLFSSL_SOURCE_DIR"
        tar -xzf "$archive" -C "$WOLFSSL_SOURCE_DIR" --strip-components=1
    fi
fi
if [ -z "$WOLFSSL_SOURCE_DIR" ]; then
    skip_step "wolfCrypt backend: no wolfSSL sources (WA_WOLFSSL_SOURCE_DIR unset and WA_NO_FETCH=1)"
else
    export WA_WOLFSSL_SOURCE_DIR="$WOLFSSL_SOURCE_DIR"
    WOLFCRYPT_FEATURES=(--no-default-features --features "backend-wolfcrypt,extended-json,wa-cbor")
    CARGO_TARGET_DIR="$BUILD_ROOT/wolfcrypt" cargo test -p wa_flightbox_backend_wolfcrypt
    CARGO_TARGET_DIR="$BUILD_ROOT/wolfcrypt" cargo test -p wa_flightbox_host_tools "${WOLFCRYPT_FEATURES[@]}"
    CARGO_TARGET_DIR="$BUILD_ROOT/wolfcrypt" cargo build -p wa_flightbox_host_tools "${WOLFCRYPT_FEATURES[@]}"
    CARGO_TARGET_DIR="$BUILD_ROOT/wolfcrypt" cargo clippy -p wa_flightbox_backend_wolfcrypt \
        -p wa_flightbox_host_tools --all-targets "${WOLFCRYPT_FEATURES[@]}" -- -D warnings
    # The build script names what is missing
    log_file="$BUILD_ROOT/refused_build.log"
    if env -u WA_WOLFSSL_SOURCE_DIR CARGO_TARGET_DIR="$BUILD_ROOT/wolfcrypt_refused"         cargo build -p wa_flightbox_backend_wolfcrypt >"$log_file" 2>&1; then
        echo "error: a wolfCrypt build without WA_WOLFSSL_SOURCE_DIR should have failed" >&2
        exit 1
    fi
    if ! grep -F "set WA_WOLFSSL_SOURCE_DIR" "$log_file" >/dev/null; then
        cat "$log_file"
        echo "error: a wolfCrypt build without WA_WOLFSSL_SOURCE_DIR does not ask for it" >&2
        exit 1
    fi
    settings_dir="$BUILD_ROOT/wolfssl_settings_without_aes_counter"
    mkdir -p "$settings_dir"
    grep -v "define WOLFSSL_AES_COUNTER" \
        "$REPOSITORY_DIR/reimplementations/c-language/config/wa_wolfssl_user_settings_for_flightbox.h" \
        >"$settings_dir/user_settings.h"
    if WA_WOLFSSL_USER_SETTINGS_DIR="$settings_dir" CARGO_TARGET_DIR="$BUILD_ROOT/wolfcrypt_refused" \
        cargo build -p wa_flightbox_backend_wolfcrypt >"$log_file" 2>&1; then
        echo "error: a wolfCrypt build without WOLFSSL_AES_COUNTER should have failed" >&2
        exit 1
    fi
    if ! grep -F "requires WOLFSSL_AES_COUNTER" "$log_file" >/dev/null; then
        cat "$log_file"
        echo "error: a wolfCrypt build without WOLFSSL_AES_COUNTER does not name the option" >&2
        exit 1
    fi
    echo "refused as expected: no WA_WOLFSSL_SOURCE_DIR, settings without WOLFSSL_AES_COUNTER"
    INTEROP_BUILD_DIRS="$INTEROP_BUILD_DIRS:$BUILD_ROOT/wolfcrypt/debug"
fi

# CROSS-COMPILATION #

for target in "${EMBEDDED_TARGETS[@]}"; do
    for feature in wa-cbor extended-json; do
        build_name="footprint_${feature//-/_}_only"
        log_step "$build_name: footprint probe, $target, RustCrypto backend"
        CARGO_TARGET_DIR="$BUILD_ROOT/$build_name" cargo build --release -p wa_flightbox_footprint_probe \
            --target "$target" --no-default-features --features "$feature"
        archive="$BUILD_ROOT/$build_name/$target/release/libwa_flightbox_footprint_probe.a"
        if command -v arm-none-eabi-ld >/dev/null 2>&1 && command -v arm-none-eabi-size >/dev/null 2>&1; then
            # What an application calling the whole API links, the Rust runtime pieces it needs included
            linked_probe="$BUILD_ROOT/$build_name/$target/release/wa_flightbox_footprint_probe.elf"
            arm-none-eabi-ld --gc-sections -e wa_flightbox_footprint_probe_run -o "$linked_probe" \
                --whole-archive "$archive" --no-whole-archive 2>/dev/null
            echo "$target $feature: $(arm-none-eabi-size "$linked_probe" | tail -n 1)"
        else
            skip_step "code size of the footprint probe: arm-none-eabi-ld or arm-none-eabi-size not found"
        fi
    done
done

# FUZZING #

log_step "Fuzz targets, $FUZZ_SECONDS s each"
if cargo +nightly fuzz --version >/dev/null 2>&1; then
    FUZZ_DIR="$BUILD_ROOT/fuzz"
    rm -rf "$FUZZ_DIR/fuzz_seeds" "$FUZZ_DIR/fuzz_artifacts"
    mkdir -p "$FUZZ_DIR"
    (cd "$REPOSITORY_DIR" && PYTHONPATH="$REPOSITORY_DIR/src${PYTHONPATH:+:$PYTHONPATH}" \
        "$PYTHON" "$REPOSITORY_DIR/reimplementations/c-language/tests/fuzz/generate_fuzz_seed_corpora.py" \
        "$FUZZ_DIR/fuzz_seeds")
    for target in wacbor_subprofile_decoder device_profile_loader; do
        corpus_dir="$FUZZ_DIR/fuzz_corpus/$target"
        artifact_dir="$FUZZ_DIR/fuzz_artifacts/$target/"
        mkdir -p "$corpus_dir" "$artifact_dir"
        echo "Fuzzing $target for $FUZZ_SECONDS s"
        (cd "$SOURCE_DIR/fuzz" && cargo +nightly fuzz run --target-dir "$FUZZ_DIR/target" "$target" \
            "$corpus_dir" "$FUZZ_DIR/fuzz_seeds/$target" -- -max_total_time="$FUZZ_SECONDS" -timeout=30 \
            -rss_limit_mb=4096 -print_final_stats=1 -artifact_prefix="$artifact_dir") \
            >"$FUZZ_DIR/$target.log" 2>&1 || {
            tail -n 60 "$FUZZ_DIR/$target.log"
            echo "error: $target found a failure, see $artifact_dir" >&2
            exit 1
        }
        grep -a "DONE\|stat::number_of_executed_units" "$FUZZ_DIR/$target.log"
        if [ -n "$(ls -A "$artifact_dir")" ]; then
            echo "error: $target left artifacts in $artifact_dir" >&2
            exit 1
        fi
    done
else
    skip_step "fuzzing: no nightly toolchain with cargo-fuzz (rustup toolchain install nightly; cargo install cargo-fuzz)"
fi

# SUPPLY CHAIN #

log_step "cargo deny"
if cargo deny --version >/dev/null 2>&1; then
    cargo deny check advisories licenses bans sources
else
    skip_step "cargo deny: not installed (cargo install cargo-deny)"
fi

log_step "All builds and tests passed"
if [ "${#SKIPPED_STEPS[@]}" -ne 0 ]; then
    echo "Skipped steps:"
    printf '  - %s\n' "${SKIPPED_STEPS[@]}"
fi
# The C builds join the interop tests when they exist: parity between the implementations is then checked
C_BUILD_ROOT="${WA_C_BUILD_ROOT:-$REPOSITORY_DIR/reimplementations/c-language/build}"
for c_build_name in gcc_mbedtls gcc_wolfcrypt; do
    if [ -x "$C_BUILD_ROOT/$c_build_name/wa_flightbox_test_driver" ]; then
        INTEROP_BUILD_DIRS="$INTEROP_BUILD_DIRS:$C_BUILD_ROOT/$c_build_name"
    fi
done
echo "$INTEROP_BUILD_DIRS" >"$BUILD_ROOT/interop_build_dirs.txt"
echo "Interop builds: WA_FLIGHTBOX_C_BUILD_DIR=$INTEROP_BUILD_DIRS"
