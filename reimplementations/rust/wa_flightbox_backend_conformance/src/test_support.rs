//! Test support shared by the workspace: the committed vector files, hex conversions, and deterministic platform
//! hooks (the generator and clock of the C library's test drivers, so that both implementations can be compared
//! byte for byte). **Never use these hooks in an encryptor**: their randomness is predictable.

